def __getattr__(name):
    if name in _RUNTIME_NAMES:
        return getattr(config, name)
    lazy = _LAZY_ATTRS.get(name)
    if lazy is not None:
        from importlib import import_module

        module = import_module(f".{lazy[0]}", __name__)
        value = getattr(module, lazy[1])
        globals()[name] = value
        return value
    deferred = _DEFERRED_ATTRS.get(name)
    if deferred is not None:
        from importlib import import_module

        module = import_module(deferred, __name__)
        if name == "__version__":
            value = module.get_project_version()
        else:
            value = getattr(module, name)
        globals()[name] = value
        return value
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
